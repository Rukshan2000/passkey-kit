// Regenerates packages/core/src/aaguids.ts from the community AAGUID list.
// Only names are copied (no icons) to keep the package small.
// Usage: node scripts/update-aaguids.mjs
import { writeFileSync } from 'node:fs';

const SOURCE = 'https://raw.githubusercontent.com/passkeydeveloper/passkey-authenticator-aaguids/main/aaguid.json';
const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`Fetch failed: ${res.status}`);
const data = await res.json();
const entries = Object.entries(data)
  .filter(([id, v]) => /^[0-9a-f-]{36}$/.test(id) && typeof v?.name === 'string')
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, v]) => `  '${id}': ${JSON.stringify(v.name)},`);

writeFileSync(
  new URL('../packages/core/src/aaguids.ts', import.meta.url),
  `// Generated by scripts/update-aaguids.mjs. Do not edit by hand.
// Source: https://github.com/passkeydeveloper/passkey-authenticator-aaguids (names only).
export const AAGUID_NAMES: Readonly<Record<string, string>> = {
${entries.join('\n')}
};
`,
);
console.log(`Wrote ${entries.length} authenticator names`);
